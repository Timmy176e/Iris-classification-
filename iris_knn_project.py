"""6.Imbalance demo"""

from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.neighbors import KNeighborsClassifier
from sklearn.dummy import DummyClassifier
from sklearn.metrics import confusion_matrix, classification_report
import pandas as pd
import numpy as np

iris = load_iris()
X = pd.DataFrame(iris.data, columns=iris.feature_names)
y = pd.Series(iris.target)

# Artificially make virginica (class 2) rare: keep only 5 of its 50 samples
rng = np.random.RandomState(42)
virginica_idx = y[y == 2].index
keep_virginica = rng.choice(virginica_idx, size=5, replace=False)
other_idx = y[y != 2].index

keep_idx = np.concatenate([other_idx, keep_virginica])
X_imb = X.loc[keep_idx]
y_imb = y.loc[keep_idx]

print("New class balance:")
print(y_imb.value_counts())

# Split + scale as before
X_train, X_test, y_train, y_test = train_test_split(
    X_imb, y_imb, test_size=0.2, random_state=42, stratify=y_imb
)
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# --- The "lazy" classifier: always predicts the majority class ---
dummy = DummyClassifier(strategy="most_frequent")
dummy.fit(X_train_scaled, y_train)
dummy_preds = dummy.predict(X_test_scaled)

print("\n=== Lazy (majority-class) classifier ===")
print("Confusion Matrix:")
print(confusion_matrix(y_test, dummy_preds))
print(classification_report(y_test, dummy_preds, target_names=iris.target_names, zero_division=0))

# --- Our actual KNN model ---
knn = KNeighborsClassifier(n_neighbors=5)
knn.fit(X_train_scaled, y_train)
knn_preds = knn.predict(X_test_scaled)

print("\n=== KNN classifier ===")
print("Confusion Matrix:")
print(confusion_matrix(y_test, knn_preds))
print(classification_report(y_test, knn_preds, target_names=iris.target_names, zero_division=0))